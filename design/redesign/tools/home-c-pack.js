// Usage: node tools/home-c-pack.js [W] [texW]
// Packs the splat inputs into home-c/scene-data.js (classic script, no fetch, works over file://).
// Colour: a texW-wide texture resampled from ../hero-campfire-original.png (each splat samples its own patch of it,
// so the still keeps photo detail beyond the W-wide splat grid and the 900-wide color.jpg).
// Depth: home-c/depth.png (read only, never rewritten) upsampled to the same grid and lightly blurred
// so canopy edges ramp instead of tearing. Both ship as base64 JPEG/PNG data URIs (data: images do not taint).
const sharp = require('/tmp/hc-npm-c/node_modules/sharp');
const fs = require('fs');
const path = require('path');
const R = path.resolve(__dirname, '..');
const W = +(process.argv[2] || 1024), TW = +(process.argv[3] || 2048);
(async () => {
  const src = path.join(R, 'hero-campfire-original.png');
  const m = await sharp(src).metadata();
  const H = Math.round(W * m.height / m.width);
  const color = await sharp(src).resize(TW, Math.round(TW * m.height / m.width), { fit: 'fill', kernel: 'lanczos3' }).removeAlpha()
    .jpeg({ quality: 80, mozjpeg: true, chromaSubsampling: '4:4:4' }).toBuffer();
  const depth = await sharp(path.join(R, 'home-c/depth.png')).greyscale().resize(W, H, { fit: 'fill' })
    .blur(1.4).png({ compressionLevel: 9, palette: false }).toBuffer();
  const js = '/* home-c scene data, generated by tools/home-c-pack.js. ' + W + 'x' + H + ' grid. */\n' +
    'window.HC_SCENE={w:' + W + ',h:' + H + ',tw:' + TW + ',' +
    'color:"data:image/jpeg;base64,' + color.toString('base64') + '",' +
    'depth:"data:image/png;base64,' + depth.toString('base64') + '"};\n';
  fs.writeFileSync(path.join(R, 'home-c/scene-data.js'), js);
  console.log('scene-data.js', W + 'x' + H, 'tex', TW, 'color', color.length, 'depth', depth.length, 'js', js.length);
})();
