// Writes public/table/js/party.js from the approved character file (Kaden 2026-11-20).
//   node scripts/build-party.mjs [scripts/data/dh-pc-characters.json]
// Character text (name, class, intro, attack names and descriptions, episodes) is copied as it is.
// Fields the file does not have (range, trait, mod, damage, type, proficiency) stay null and the card
// shows "to come". `anim` and `bolt` are the table's own: which attack.js animation plays and its colour,
// chosen from each attack's animation_idea (RobBot's plan, section 3).
import fs from 'node:fs';

const src = process.argv[2] || new URL('./data/dh-pc-characters.json', import.meta.url).pathname;
const out = new URL('../public/table/js/party.js', import.meta.url).pathname;
const data = JSON.parse(fs.readFileSync(src, 'utf8'));

// attack slug -> [anim, bolt colour]. lunge = the piece steps in and strikes; bolt = a streak leaves
// the piece; magic = a glowing burst leaves the piece. The colour is the effect's, from the idea's palette.
const ANIM = {
  'unstoppable': ['magic', 0xffd45a], 'shield-charge': ['lunge'], 'i-am-your-shield': ['magic', 0x8fc8ff],
  'unleash-chaos': ['magic', 0xff3a52], 'chained-kunai-and-chokehold': ['bolt', 0xff4a5e], 'feather-blades': ['bolt', 0xff8cc4],
  'finishing-blast': ['magic', 0xb27cff], 'invisibility-ambush': ['lunge'], 'rally-and-relaxing-song': ['magic', 0xf0b8ff],
  'power-push': ['magic', 0xcfe6ff], 'ice-spike': ['magic', 0x86e2ff], 'not-this-time': ['magic', 0xb9c6ff],
  'whirlwind': ['lunge'], 'faun-kick': ['lunge'], 'no-mercy': ['lunge'],
  'reign-of-blades': ['bolt', 0x8a7bd8], 'shadow-sneak-attack': ['lunge'], 'veil-of-night': ['magic', 0x5a4c86],
  'combo-strike': ['lunge'], 'bare-knuckle-punch': ['lunge'], 'arcane-charged-punch': ['lunge'],
  'pack-predator-beastform': ['lunge'], 'water-elemental-surge': ['magic', 0x4aa8ff], 'fire-incarnation': ['bolt', 0xff8a3a],
};
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const party = data.characters.map((c) => ({
  id: c.id, node: c.node, mini: c.id, name: c.name, class: c.class, intro: c.intro,
  proficiency: null,
  attacks: c.attacks.map((a) => {
    const id = slug(a.name), [anim, bolt] = ANIM[id] || (() => { throw new Error('no animation chosen for ' + id); })();
    return { id, name: a.name, description: a.description, animation_idea: a.animation_idea, episodes: a.episodes,
      range: null, trait: null, mod: null, damage: null, type: null, anim, ...(bolt != null ? { bolt } : {}) };
  }),
}));

const json = JSON.stringify(party, null, 2).replace(/"bolt": (\d+)/g, (_, n) => '"bolt": 0x' + (+n).toString(16).padStart(6, '0'));
fs.writeFileSync(out, `// GENERATED by scripts/build-party.mjs from scripts/data/dh-pc-characters.json (content approved by Kaden 2026-11-20). Do not edit the text here.
// id         the glb's file stem (models/pc/<id>.glb); node is the glTF root node's name in that file
// range, trait, mod, damage, type, proficiency: not in the approved file, so null; the card reads "to come"
// anim       'lunge' | 'bolt' | 'magic' (attack.js); bolt is the effect's colour
export const PARTY = ${json.replace(/"([a-z_]+)":/g, '$1:')};
`);
console.log('wrote', out, party.length, 'characters');
